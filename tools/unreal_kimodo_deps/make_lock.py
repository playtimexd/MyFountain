"""Regenerate the KimodoDeps Unreal plugin from requirements.in.

Unreal's PythonScriptPlugin installs a plugin's "PythonRequirements" into <Project>/Intermediate/PipInstall every time
the editor starts, but only as wheels (--only-binary=:all:) and, by default, only fully pinned with hashes
(--require-hashes).  So this script:
  1. makes a scratch venv from Unreal's own Python (same version / platform the editor will install for),
  2. builds the one dependency that has no wheel (antlr4-python3-runtime 4.9.3, needed by hydra-core / omegaconf) and
     ships it inside the plugin (Content/Python/Lib/site-packages - Unreal links that folder into the pip environment),
  3. resolves everything else with `pip install --dry-run --report` (reads package metadata only, installs nothing),
  4. writes KimodoDeps/KimodoDeps.uplugin (every package pinned with its sha256) and requirements.lock.txt.

usage:  python make_lock.py ["C:/Program Files/Epic Games/UE_5.9"]
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLUGIN = HERE / "KimodoDeps"
EXTRA_INDEX = "https://download.pytorch.org/whl/cu128"
VENDORED = {"antlr4-python3-runtime": "4.9.3"}          # no wheel on PyPI; shipped inside the plugin


def run(cmd: list[str], **kw) -> None:
    print(">", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, **kw)


def main() -> None:
    ue = Path(sys.argv[1] if len(sys.argv) > 1 else r"C:\Program Files\Epic Games\UE_5.9")
    uepy = ue / "Engine/Binaries/ThirdParty/Python3/Win64/python.exe"
    if not uepy.exists():
        sys.exit(f"Unreal's Python not found: {uepy}")
    with tempfile.TemporaryDirectory(prefix="kimodo_lock_") as tmp:
        tmp = Path(tmp)
        run([str(uepy), "-m", "venv", str(tmp / "venv")])
        py = str(tmp / "venv/Scripts/python.exe")
        pip = [py, "-I", "-m", "pip", "--disable-pip-version-check"]
        # 2. the vendored sdist-only package: build its wheel, unpack it into the plugin, install it into the scratch venv
        wheels = tmp / "wheels"
        for name, ver in VENDORED.items():
            run(pip + ["wheel", "--no-deps", "-w", str(wheels), f"{name}=={ver}"])
        site = PLUGIN / "Content/Python/Lib/site-packages"
        if site.exists():
            shutil.rmtree(site)
        site.mkdir(parents=True)
        for whl in wheels.glob("*.whl"):
            with zipfile.ZipFile(whl) as z:
                z.extractall(site)
            run(pip + ["install", "--no-deps", "--no-index", str(whl)])
        # 3. resolve the rest exactly the way the editor will install it
        report = tmp / "report.json"
        run(pip + ["install", "--dry-run", "--only-binary=:all:", "--extra-index-url", EXTRA_INDEX, "--report", str(report),
                   "-r", str(HERE / "requirements.in")])
        inst = json.loads(report.read_text("utf-8"))["install"]
    lines = []
    for i in sorted(inst, key=lambda i: i["metadata"]["name"].lower()):
        name, ver = i["metadata"]["name"], i["metadata"]["version"]
        if name.lower() in VENDORED:
            continue
        sha = i["download_info"]["archive_info"]["hashes"]["sha256"]
        lines.append(f"{name}=={ver} --hash=sha256:{sha}")
    torch = next(l for l in lines if l.lower().startswith("torch=="))
    if "+cu" not in torch:
        sys.exit(f"resolved a CPU-only torch ({torch.split()[0]}): pin a +cu128 version in requirements.in")
    (HERE / "requirements.lock.txt").write_text(
        "# generated by make_lock.py from requirements.in - do not edit\n"
        f"# install:  python -m pip install --only-binary=:all: --require-hashes --extra-index-url {EXTRA_INDEX} -r requirements.lock.txt\n"
        + "\n".join(lines) + "\n", "utf-8")
    desc = json.loads((PLUGIN / "KimodoDeps.uplugin").read_text("utf-8"))
    desc["PythonRequirements"] = [{"Platform": "Win64", "Requirements": lines, "ExtraIndexUrls": [EXTRA_INDEX]}]
    (PLUGIN / "KimodoDeps.uplugin").write_text(json.dumps(desc, indent="\t") + "\n", "utf-8")
    print(f"{len(lines)} packages locked (+ {', '.join(VENDORED)} vendored); torch: {torch.split()[0]}")


if __name__ == "__main__":
    main()
