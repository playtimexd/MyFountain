"""CREDITS.md export (grouped by licence, attribution-required entries first)."""
from __future__ import annotations

import time

from . import db, licenses
from .connectors.cmu import ACK


def credits_md(asset_ids: list[str] | None = None, title: str = "Credits") -> str:
    if asset_ids:
        assets = [a for a in (db.get(i, full=False) for i in asset_ids) if a]
    else:
        assets = db.search({}, page=1, page_size=200)["items"]
        page = 2
        while len(assets) < 20000:
            more = db.search({}, page=page, page_size=200)
            assets += more["items"]
            if not more["has_more"]:
                break
            page += 1
    groups: dict[str, list[dict]] = {}
    for a in assets:
        groups.setdefault(a["license"], []).append(a)
    order = sorted(groups, key=lambda l: (not licenses.info(l)["attribution_required"], l))
    out = [f"# {title}", "", f"_Generated by CutLab Asset Hub on {time.strftime('%Y-%m-%d')} - {len(assets)} asset(s)._", ""]
    for lic in order:
        i = licenses.info(lic)
        out.append(f"## {i['label']}" + (f" ({i['url']})" if i["url"] else ""))
        if not i["attribution_required"]:
            out.append("_Attribution not required - listed as a courtesy._")
        if not i["commercial_ok"]:
            out.append("**Non-commercial licence: do not use these in a commercial product.**")
        out.append("")
        for a in sorted(groups[lic], key=lambda a: (a["source"], a["name"].lower())):
            out.append(f"- {a.get('attribution') or a['name']}")
        out.append("")
    used = {a["source"] for a in assets}
    notes = []
    if "polyhaven" in used:
        notes.append("- Some assets come from Poly Haven (https://polyhaven.com) - thank you!")
    if "cmu" in used:
        notes.append(f"- Motion capture: {ACK}")
    if "freesound" in used:
        notes.append("- Sounds from Freesound (https://freesound.org).")
    if "sketchfab" in used:
        notes.append("- 3D models from Sketchfab (https://sketchfab.com).")
    if notes:
        out += ["## Sources", "", *notes, ""]
    return "\n".join(out)
